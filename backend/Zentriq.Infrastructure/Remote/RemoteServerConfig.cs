using System.Text.Json.Nodes;

namespace Zentriq.Infrastructure.Remote;

/// <summary>
/// Builds the configuration (config.json) of the bundled MeshCentral server with Zentriq branding: titles and logo,
/// agent name, service name and icon, consent prompt texts; only token sign-in (no password page, no self sign-up),
/// no Intel AMT or HTTP ports, no self-update. Written by zentriqctl at install, repair and upgrade.
/// </summary>
public static class RemoteServerConfig
{
    public sealed record Input(string HostName, int Port, string LoginKeyHex, string SessionKey, string DataPath, string FilesPath, string BackupPath);

    public const string TitlePicture = "remote-title.png";
    public const string AgentImage = "remote-agent.png";
    public const string AgentIcon = "remote-agent.ico";

    public static JsonObject Build(Input i) => new()
    {
        ["$schema"] = "https://raw.githubusercontent.com/Ylianst/MeshCentral/master/meshcentral-config-schema.json",
        ["__comment__"] = "Generated by Zentriq Setup. Changes are overwritten at the next repair or upgrade.",
        ["settings"] = new JsonObject
        {
            // MeshCentral switches to LAN-only mode (agents look for the server by multicast) when the certificate name has
            // no dot. Devices connect to agentAliasDNS (the real host name), so a trailing dot keeps WAN mode for names such as
            // "localhost" or a NetBIOS server name.
            ["cert"] = CertificateName(i.HostName),
            ["port"] = i.Port,
            ["redirPort"] = 0,
            ["mpsPort"] = 0,
            ["exactPorts"] = true,
            ["WANonly"] = true,
            ["agentAliasDNS"] = i.HostName,
            ["datapath"] = i.DataPath,
            ["filespath"] = i.FilesPath,
            ["LoginCookieEncryptionKey"] = i.LoginKeyHex,
            ["allowLoginToken"] = true,
            ["allowFraming"] = false,
            ["sessionKey"] = i.SessionKey,
            ["no2FactorAuth"] = true,
            ["selfUpdate"] = false,
            ["compression"] = true,
            ["webRTC"] = false,
            ["agentPong"] = 300,
            ["browserPing"] = 60,
            ["plugins"] = new JsonObject { ["enabled"] = false },
            ["autoBackup"] = new JsonObject { ["backupIntervalHours"] = 24, ["keepLastDaysBackup"] = 14, ["backupPath"] = i.BackupPath },
        },
        ["domains"] = new JsonObject
        {
            [""] = new JsonObject
            {
                ["title"] = "Zentriq",
                ["title2"] = "Remote Support",
                ["titlePicture"] = TitlePicture,
                ["welcomeText"] = "Zentriq Remote Support. Open remote sessions from the Zentriq console (Remote Management).",
                ["footer"] = "Zentriq Remote Support",
                ["loginfooter"] = "Zentriq Remote Support",
                ["newAccounts"] = false,
                ["showPasswordLogin"] = false,
                ["nightMode"] = 2,
                ["siteStyle"] = 2,
                ["myServer"] = false,
                ["novnc"] = false,
                ["mstsc"] = false,
                ["ssh"] = false,
                ["agentCustomization"] = new JsonObject
                {
                    ["displayName"] = "Zentriq Remote Support",
                    ["description"] = "Zentriq Remote Support agent (lets your IT team help you remotely)",
                    ["companyName"] = "Zentriq",
                    ["serviceName"] = "ZentriqRemoteSupport",
                    ["fileName"] = "ZentriqRemoteSupport",
                    ["installText"] = "Zentriq Remote Support lets your IT team help you remotely. You are asked before anyone can see or control this computer.",
                    ["image"] = AgentImage,
                    ["foregroundColor"] = "#FFFFFF",
                    ["backgroundColor"] = "#0F4C5C",
                },
                ["agentFileInfo"] = new JsonObject
                {
                    ["icon"] = AgentIcon,
                    ["fileDescription"] = "Zentriq Remote Support Agent",
                    ["productName"] = "Zentriq Remote Support",
                    ["internalName"] = "ZentriqRemoteSupport",
                    ["originalFilename"] = "ZentriqRemoteSupport.exe",
                    ["legalCopyright"] = "Zentriq. Includes MeshCentral agent software, Apache License 2.0.",
                },
                ["consentMessages"] = new JsonObject
                {
                    ["Title"] = "Zentriq Remote Support",
                    ["Desktop"] = "{0} from your IT team wants to see and control your screen. Allow?",
                    ["Terminal"] = "{0} from your IT team wants to open a command window on this computer. Allow?",
                    ["Files"] = "{0} from your IT team wants to access the files on this computer. Allow?",
                    ["consentTimeout"] = 60,
                    ["autoAcceptOnTimeout"] = false,
                },
            },
        },
    };

    /// <summary>The certificate name for MeshCentral: the host name, with a trailing dot when it has no dot.</summary>
    public static string CertificateName(string host) =>
        host.Contains('.') || System.Net.IPAddress.TryParse(host, out _) ? host : host + ".";
}
